(ns haselnuss.library.catechism-test
  "The milestone's acceptance test (TASK-159; doc-10, \"Success criteria\"
  and \"Testing strategy\"): the Heidelberg catechism quotes its proof texts
  from a Bible library instead of copying them, and reads the same.

  The fixtures:

  - `test/fixtures/libraries/bible/` -- a filesystem library whose shelf
    `nt/` is generated by `shelf.clj` over `almeida.json`, a sample of the
    Almeida text the example copies, holding exactly the verses the excerpt
    cites. Its licence is unverified: the upstream source withdrew the text
    for that reason. Its README records what is known, and the replacement
    text is an open decision on TASK-159;
  - `test/fixtures/catechism/catecismo-domingo-1.hdoc` -- the first
    Lord's Day of `examples/catecismo-heidelberg.hdoc`, every
    `small-collapsable` proof text a `!quote bible:<slug>#<locator>` line;
  - `test/fixtures/catechism/libraries.yaml` -- its library directory,
    `scripts: true`.

  The copied-verse version is not a second fixture: it is cut out of
  `examples/catecismo-heidelberg.hdoc` itself at build time (its front
  matter, and Lord's Day 1 up to question 2), so the comparison is always
  against the example as committed.

  The `:memory` build hands `haselnuss.cli/build` a LibraryDirectory value
  (`:library-directory`) of in-process virtual books written here in
  Clojure over the same JSON -- the same document, the same pipeline, a
  different kind of book."
  (:require [clojure.data.json :as json]
            [clojure.java.io :as io]
            [clojure.java.shell :as shell]
            [clojure.string :as str]
            [clojure.test :refer [deftest is testing]]
            [haselnuss.book-ref :as book-ref]
            [haselnuss.cli :as cli]
            [haselnuss.library :as library]
            [haselnuss.library.memory :as memory])
  (:import (java.io File)
           (java.nio.file Files)
           (java.nio.file.attribute FileAttribute)))

;; --- fixtures ----------------------------------------------------------------

(def ^:private catechism-dir (io/file "test/fixtures/catechism"))

(def ^:private quoted-source (io/file catechism-dir "catecismo-domingo-1.hdoc"))

(def ^:private libraries-file (io/file catechism-dir "libraries.yaml"))

(def ^:private example-file (io/file "examples/catecismo-heidelberg.hdoc"))

(def ^:private almeida-file (io/file "test/fixtures/libraries/bible/nt/almeida.json"))

(def ^:private no-env
  "Never read the real `$HASELNUSS_LIBRARIES` or home config."
  {:library-env {} :library-home "/nonexistent/haselnuss-test-home"})

(defn- temp-dir ^File []
  (.toFile (Files/createTempDirectory "haselnuss-catechism" (make-array FileAttribute 0))))

(defn- copied-excerpt
  "The copied-verse version of the excerpt, cut out of the committed
  example: its front matter, then from `## Domingo 1` up to (not
  including) question 2."
  []
  (let [lines (str/split-lines (slurp example-file))
        front-end (inc (.indexOf ^java.util.List (vec (rest lines)) "---"))
        start (.indexOf ^java.util.List lines "## Domingo 1")
        end (first (keep-indexed (fn [i l] (when (str/starts-with? l "### 2. ") i)) lines))]
    (assert (and (pos? front-end) (pos? start) (> end start)) "the example's excerpt moved")
    (str (str/join "\n" (take (inc front-end) lines)) "\n\n"
         (str/join "\n" (subvec (vec lines) start end)) "\n")))

;; --- HTML scraping -----------------------------------------------------------

(defn- unescape [s]
  (-> s (str/replace "&lt;" "<") (str/replace "&gt;" ">") (str/replace "&quot;" "\"")
      (str/replace "&#39;" "'") (str/replace "&amp;" "&")))

(defn- text-of
  "The text a reader sees in an HTML fragment: tags dropped, whitespace
  collapsed."
  [html]
  (-> html (str/replace #"<[^>]*>" " ") unescape (str/replace #"\s+" " ") str/trim))

(defn- proof-texts
  "Every `small-collapsable` of `html`, in order, as `[summary body-html]`."
  [html]
  (mapv (fn [[_ summary body]] [(unescape summary) body])
        (re-seq #"(?s)<details class=\"small-collapsable\"><summary>(.*?)</summary><div class=\"small-collapsable-body\">(.*?)</div></details>"
                html)))

(def ^:private book-quote-re
  #"(?s)<figure class=\"book-quote-figure\"><blockquote class=\"book-quote\" data-source=\"([^\"]*)\">(.*?)</blockquote><figcaption>— <cite>(.*?)</cite></figcaption></figure>")

(defn- book-quote
  "A proof text's body that is exactly one book quote, as `{:source :html
  :title}`, or nil."
  [body]
  (when-let [[_ source inner title] (re-matches book-quote-re body)]
    {:source (unescape source) :html inner :title (unescape title)}))

;; --- builds ------------------------------------------------------------------

(defn- build-html
  "`haselnuss.cli/build` of `input` to HTML in `dir`, with `opts`. Returns
  `{:html :diagnostics}`."
  [^File dir input opts]
  (let [out (io/file dir (str (.getName (io/file input)) ".html"))
        result (cli/build (merge no-env {:input (str input) :target "html" :output (str out)} opts))]
    {:html (slurp out) :diagnostics (:diagnostics result)}))

(defn- build-copied []
  (let [dir (temp-dir)
        input (io/file dir "copied.hdoc")]
    (spit input (copied-excerpt))
    (build-html dir input {})))

(defn- build-quoted
  ([] (build-quoted {:libraries (str libraries-file)}))
  ([opts] (build-html (temp-dir) quoted-source opts)))

;; --- the :memory Bible -------------------------------------------------------

(defn- verse-para [text] {:t :para :inlines [{:t :str :text text}]})

(defn- numbered-para [verse text]
  {:t :para :inlines [{:t :strong :inlines [{:t :str :text (str verse)}]}
                      {:t :str :text (str " " text)}]})

(defn- memory-bible
  "A LibraryDirectory holding one `:memory` library, `bible`, whose books
  are Clojure virtual books over almeida.json on the shelf `nt` -- written
  independently of `shelf.clj`, as an embedding program would."
  []
  (let [books (json/read-str (slurp almeida-file) :key-fn keyword)]
    (library/library-directory
     [(memory/memory-library
       {:name "bible"
        :books
        (for [{:keys [slug title verses]} books]
          {:id (book-ref/book-id "bible" ["nt"] slug)
           :entry {:title title :lang "pt-BR"}
           :document (fn [] {:meta {:title [{:t :str :text title}] :lang "pt-BR"}
                             :blocks (mapv (fn [[_ v text]] (numbered-para v text)) verses)})
           :locate (fn [locator]
                     (let [[_ c from to] (re-matches #"(\d+):(\d+)(?:-(\d+))?" locator)
                           [c from] (map parse-long [c from])
                           to (if to (parse-long to) from)
                           found (filter (fn [[ch v]] (and (= c ch) (<= from v to))) verses)]
                       (cond
                         (empty? found)
                         {:type :bad-locator :message (str "no verse " locator)}
                         (= 1 (count found))
                         {:title (str title " " locator) :blocks [(verse-para (nth (first found) 2))]}
                         :else
                         {:title (str title " " locator)
                          :blocks (mapv (fn [[_ v text]] (numbered-para v text)) found)})))})})])))

;; --- tests -------------------------------------------------------------------

(deftest quoted-catechism-reads-like-the-copied-one-test
  (let [copied (build-copied)
        quoted (build-quoted)
        copied-texts (proof-texts (:html copied))
        quoted-texts (proof-texts (:html quoted))]
    (testing "both build with no diagnostics at all"
      (is (= [] (:diagnostics copied)) (pr-str (:diagnostics copied)))
      (is (= [] (:diagnostics quoted)) (pr-str (:diagnostics quoted))))

    (testing "the excerpt is the whole of Lord's Day 1, question 1: 31 proof
              texts, two of them verse ranges"
      (is (= 31 (count copied-texts)))
      (is (= (map first copied-texts) (map first quoted-texts))
          "the same proof texts, under the same summaries, in the same order"))

    (testing "AC #1: each proof text carries the same verse text as the
              copied version -- and the same markup, verse numbers included"
      (doseq [[[summary copied-body] [_ quoted-body]] (map vector copied-texts quoted-texts)]
        (let [{:keys [html]} (book-quote quoted-body)]
          (is (some? html) (str summary ": not a single book quote: " quoted-body))
          (is (= (text-of copied-body) (text-of (or html ""))) summary)
          (is (= copied-body html) summary)))
      (is (re-find #"<p><strong>34</strong> Replicou-lhes Jesus:" (:html quoted))
          "a verse range keeps its verse numbers"))

    (testing "AC #2: each quoted verse sits in a book-quote blockquote whose
              data-source is its canonical book ID (with the passage), and
              its caption names the passage"
      (let [listed (cli/list-books (merge no-env {:libraries (str libraries-file)}) "bible")
            canonical (into {} (for [[id _] (:books listed)]
                                 [(:slug (:id (book-ref/parse-book-ref id))) id]))]
        (is (= [] (:diagnostics listed)) (pr-str (:diagnostics listed)))
        (is (= 13 (count canonical)) "one generated book per book of almeida.json")
        (is (= 31 (count (re-seq #"<blockquote class=\"book-quote\"" (:html quoted))))
            "one blockquote per proof text, and no other")
        (doseq [[summary body] quoted-texts]
          (let [{:keys [source title]} (book-quote body)
                [_ slug locator] (re-matches #"bible:nt/([a-z0-9-]+)#(.+)" (str source))]
            (is (= (str (canonical slug) "#" locator) source) summary)
            (is (str/starts-with? source "bible:nt/") (str summary " -> " source))
            (is (str/ends-with? summary (str " " locator)) (str summary " -> " source))
            (is (= summary title))))))))

(deftest memory-bible-is-interchangeable-test
  (testing "AC #3: the same document built against a :memory library of
            in-process virtual books (no libraries.yaml, no shelf.clj)
            produces the same verse text, under the same sources"
    (let [generated (build-quoted)
          virtual (build-quoted {:library-directory (memory-bible)})]
      (is (= [] (:diagnostics virtual)) (pr-str (:diagnostics virtual)))
      (is (= 31 (count (proof-texts (:html virtual)))))
      (is (= (mapv (fn [[s body]] [s (text-of body)]) (proof-texts (:html generated)))
             (mapv (fn [[s body]] [s (text-of body)]) (proof-texts (:html virtual)))))
      (is (= (:html generated) (:html virtual))
          "byte for byte: nothing in the output says which kind of book it was")))
  (testing ":library-directory also serves --list-books, which reads no
            directory file at all with it (no :libraries here)"
    (let [{:keys [books diagnostics]} (cli/list-books (merge no-env {:library-directory (memory-bible)})
                                                      "bible")]
      (is (= [] diagnostics))
      (is (= 13 (count books)))
      (is (= ["bible:nt/joao" "João"] (first (filter #(= "bible:nt/joao" (first %)) books)))))))

(defn- quote-of
  "Builds a one-quote document against the fixture library; returns
  `{:html :diagnostics}`."
  [written]
  (let [dir (temp-dir)
        input (io/file dir "q.hdoc")]
    (spit input (str "# Q\n\n!quote " written "\n"))
    (build-html dir input {:libraries (str libraries-file)})))

(deftest fixture-locators-test
  (testing "a reversed range is reported as reversed, not as missing"
    (let [{:keys [html diagnostics]} (quote-of "bible:joao#8:36-34")]
      (is (= [:bad-locator] (mapv :type diagnostics)) (pr-str diagnostics))
      (is (re-find #"reversed range" (:message (first diagnostics))))
      (is (str/includes? html "?? bible:joao#8:36-34"))))
  (testing "a range only partly in the sample is rejected"
    (let [{:keys [diagnostics]} (quote-of "bible:joao#8:33-35")]
      (is (= [:bad-locator] (mapv :type diagnostics)))
      (is (re-find #"only partly" (:message (first diagnostics))))))
  (testing "a bare chapter answers the verses the sample holds of it, as
            shelf.clj documents -- it cannot know the chapter's length"
    (let [{:keys [html diagnostics]} (quote-of "bible:joao#8")]
      (is (= [] diagnostics) (pr-str diagnostics))
      (is (= ["34" "35" "36"] (map second (re-seq #"<strong>(\d+)</strong>" html)))))))

(deftest quoted-catechism-compiles-to-pdf-test
  (testing "the quoted excerpt's LaTeX compiles, each quote a quote
            environment closed by its source line"
    (let [dir (temp-dir)
          tex (io/file dir "catecismo.tex")
          {:keys [diagnostics]} (cli/build (merge no-env {:input (str quoted-source) :target "latex"
                                                          :libraries (str libraries-file)
                                                          :output (str tex)}))
          latex (slurp tex)]
      (is (= [] diagnostics) (pr-str diagnostics))
      (is (= 31 (count (re-seq #"(?m)^\\begin\{quote\}$" latex))))
      (is (str/includes? latex "\\textbf{34} Replicou-lhes Jesus:"))
      (is (str/includes? latex "{\\raggedleft --- João 8:34-36\\par}"))
      (dotimes [_ 2]
        (shell/sh "pdflatex" "-interaction=nonstopmode" "-halt-on-error" "catecismo.tex" :dir (str dir)))
      (is (.isFile (io/file dir "catecismo.pdf")) "pdflatex must produce a PDF")
      (let [pdf (:out (shell/sh "pdftotext" (str (io/file dir "catecismo.pdf")) "-"))]
        (is (= 31 (count (re-seq #"(?m)^— " pdf))) "one source line per quote")
        (is (str/includes? pdf "Eu e o Pai somos um."))))))
