(ns haselnuss.library.catechism-test
  "The milestone's acceptance test (TASK-159; doc-10, \"Success criteria\"
  and \"Testing strategy\"), moved onto a verifiably licensed text in
  TASK-212: the Heidelberg catechism quotes its proof texts from a Bible
  library instead of copying them.

  The data:

  - `examples/libraries/bible/` -- a filesystem library whose shelf
    `blivre/` is generated by `shelf.clj` over `blivre.json`, the verses
    `examples/catecismo-heidelberg.hdoc` cites, from the Bíblia Livre
    (CC BY 3.0 Brasil). Its README records edition, licence evidence,
    attribution and the changes made to the text;
  - `examples/libraries/libraries.yaml` -- its library directory,
    `scripts: true`;
  - `examples/catecismo-heidelberg.hdoc` -- the whole example: every proof
    text a `!quote bible:<slug>#<locator>` line but two references that do
    not exist in the original catechism either.

  The excerpt the PDF and `:memory` tests build is not a second fixture: it
  is cut out of the example at build time (its front matter, and Lord's Day
  1 up to question 2), so it is always the example as committed.

  The verse text each quote must show is read straight from `blivre.json`
  here, independently of `shelf.clj`. The `:memory` build hands
  `haselnuss.cli/build` a LibraryDirectory value (`:library-directory`) of
  in-process virtual books written here in Clojure over the same JSON -- the
  same document, the same pipeline, a different kind of book."
  (:require [clojure.data.json :as json]
            [clojure.java.io :as io]
            [clojure.java.shell :as shell]
            [clojure.string :as str]
            [clojure.test :refer [deftest is testing]]
            [haselnuss.book-ref :as book-ref]
            [haselnuss.cli :as cli]
            [haselnuss.library :as library]
            [haselnuss.library.memory :as memory])
  (:import (java.io File)
           (java.nio.file Files)
           (java.nio.file.attribute FileAttribute)))

;; --- fixtures ----------------------------------------------------------------

(def ^:private libraries-file (io/file "examples/libraries/libraries.yaml"))

(def ^:private example-file (io/file "examples/catecismo-heidelberg.hdoc"))

(def ^:private bible-dir (io/file "examples/libraries/bible"))

(def ^:private blivre-file (io/file bible-dir "blivre/blivre.json"))

(def ^:private blivre-books
  "blivre.json as read here: `[{:slug :title :verses [[c v text] ...]}]`."
  (delay (json/read-str (slurp blivre-file) :key-fn keyword)))

(def ^:private no-env
  "Never read the real `$HASELNUSS_LIBRARIES` or home config."
  {:library-env {} :library-home "/nonexistent/haselnuss-test-home"})

(defn- temp-dir ^File []
  (.toFile (Files/createTempDirectory "haselnuss-catechism" (make-array FileAttribute 0))))

(defn- excerpt
  "The excerpt, cut out of the committed example: its front matter, then
  from `## Domingo 1` up to (not including) question 2."
  []
  (let [lines (str/split-lines (slurp example-file))
        front-end (inc (.indexOf ^java.util.List (vec (rest lines)) "---"))
        start (.indexOf ^java.util.List lines "## Domingo 1")
        end (first (keep-indexed (fn [i l] (when (str/starts-with? l "### 2. ") i)) lines))]
    (assert (and (pos? front-end) (pos? start) (> end start)) "the example's excerpt moved")
    (str (str/join "\n" (take (inc front-end) lines)) "\n\n"
         (str/join "\n" (subvec (vec lines) start end)) "\n")))

;; --- HTML scraping -----------------------------------------------------------

(defn- unescape [s]
  (-> s (str/replace "&lt;" "<") (str/replace "&gt;" ">") (str/replace "&quot;" "\"")
      (str/replace "&#39;" "'") (str/replace "&amp;" "&")))

(defn- text-of
  "The text a reader sees in an HTML fragment: tags dropped, whitespace
  collapsed."
  [html]
  (-> html (str/replace #"<[^>]*>" " ") unescape (str/replace #"\s+" " ") str/trim))

(defn- proof-texts
  "Every `small-collapsable` of `html`, in order, as `[summary body-html]`."
  [html]
  (mapv (fn [[_ summary body]] [(unescape summary) body])
        (re-seq #"(?s)<details class=\"small-collapsable\"><summary>(.*?)</summary><div class=\"small-collapsable-body\">(.*?)</div></details>"
                html)))

(def ^:private book-quote-re
  #"(?s)<figure class=\"book-quote-figure\"><blockquote class=\"book-quote\" data-source=\"([^\"]*)\">(.*?)</blockquote><figcaption>— <cite>(.*?)</cite></figcaption></figure>")

(defn- book-quote
  "A proof text's body that is exactly one book quote, as `{:source :html
  :title}`, or nil."
  [body]
  (when-let [[_ source inner title] (re-matches book-quote-re body)]
    {:source (unescape source) :html inner :title (unescape title)}))

;; --- builds ------------------------------------------------------------------

(defn- build-html
  "`haselnuss.cli/build` of `input` to HTML in `dir`, with `opts`. Returns
  `{:html :diagnostics}`."
  [^File dir input opts]
  (let [out (io/file dir (str (.getName (io/file input)) ".html"))
        result (cli/build (merge no-env {:input (str input) :target "html" :output (str out)} opts))]
    {:html (slurp out) :diagnostics (:diagnostics result)}))

(defn- excerpt-file
  "The excerpt written to a fresh temporary directory."
  ^File []
  (let [input (io/file (temp-dir) "domingo-1.hdoc")]
    (spit input (excerpt))
    input))

(defn- build-excerpt
  ([] (build-excerpt {:libraries (str libraries-file)}))
  ([opts] (let [input (excerpt-file)]
            (build-html (.getParentFile input) input opts))))

(def ^:private example-build
  "The whole example built to HTML against the committed library, once."
  (delay (build-html (temp-dir) example-file {:libraries (str libraries-file)})))

;; --- what the library says a passage reads -----------------------------------

(def ^:private slug-of-title (delay (into {} (map (juxt :title :slug)) @blivre-books)))

(defn- passage-of
  "A proof-text summary such as `João 8:34-36` or `Gênesis 3` as `{:slug
  :locator :verses}`, the verses read from blivre.json: `[[v text] ...]`."
  [summary]
  (let [[_ title chapter from to] (re-matches #"(.*) (\d+)(?::(\d+)(?:-(\d+))?)?" summary)
        slug (@slug-of-title title)
        [chapter from] (map #(some-> % parse-long) [chapter from])
        to (or (some-> to parse-long) from)
        book (first (filter #(= slug (:slug %)) @blivre-books))]
    {:slug slug
     :locator (second (re-matches #".* (\d+(?::\d+(?:-\d+)?)?)" summary))
     :verses (vec (for [[c v text] (:verses book)
                        :when (and (= c chapter) (or (nil? from) (<= from v to)))]
                    [v text]))}))

(defn- expected-text
  "What a reader should see for the passage: the verse itself, or each verse
  after its number."
  [{:keys [verses]}]
  (if (= 1 (count verses))
    (second (first verses))
    (str/join " " (mapcat (fn [[v text]] [(str v) text]) verses))))

;; --- the :memory Bible -------------------------------------------------------

(defn- verse-para [text] {:t :para :inlines [{:t :str :text text}]})

(defn- numbered-para [verse text]
  {:t :para :inlines [{:t :strong :inlines [{:t :str :text (str verse)}]}
                      {:t :str :text (str " " text)}]})

(defn- memory-bible
  "A LibraryDirectory holding one `:memory` library, `bible`, whose books
  are Clojure virtual books over blivre.json on the shelf `blivre` -- written
  independently of `shelf.clj`, as an embedding program would. Its locators
  are `C:V` and `C:V-W` only; a bare chapter is the generated shelf's."
  []
  (let [books @blivre-books]
    (library/library-directory
     [(memory/memory-library
       {:name "bible"
        :books
        (for [{:keys [slug title verses]} books]
          {:id (book-ref/book-id "bible" ["blivre"] slug)
           :entry {:title title :lang "pt-BR"}
           :document (fn [] {:meta {:title [{:t :str :text title}] :lang "pt-BR"}
                             :blocks (mapv (fn [[_ v text]] (numbered-para v text)) verses)})
           :locate (fn [locator]
                     (let [[_ c from to] (re-matches #"(\d+):(\d+)(?:-(\d+))?" locator)
                           [c from] (map parse-long [c from])
                           to (if to (parse-long to) from)
                           found (filter (fn [[ch v]] (and (= c ch) (<= from v to))) verses)]
                       (cond
                         (empty? found)
                         {:type :bad-locator :message (str "no verse " locator)}
                         (= 1 (count found))
                         {:title (str title " " locator) :blocks [(verse-para (nth (first found) 2))]}
                         :else
                         {:title (str title " " locator)
                          :blocks (mapv (fn [[_ v text]] (numbered-para v text)) found)})))})})])))

;; --- tests -------------------------------------------------------------------

(deftest example-quotes-every-proof-text-from-the-library-test
  (let [{:keys [html diagnostics]} @example-build
        source (slurp example-file)
        texts (proof-texts html)
        listed (cli/list-books (merge no-env {:libraries (str libraries-file)}) "bible")
        canonical (into {} (for [[id _] (:books listed)]
                             [(:slug (:id (book-ref/parse-book-ref id))) id]))
        quoted (remove (comp #(str/includes? % "não localizada") second) texts)]
    (testing "the whole example builds with no diagnostics at all"
      (is (= [] diagnostics) (pr-str diagnostics))
      (is (= [] (:diagnostics listed)) (pr-str (:diagnostics listed))))

    (testing "AC #2: no verse is copied into the example: 1,425 proof texts,
              1,423 of them a `!quote` line and the two references this
              edition's versification lacks (João 15:35, 1 Samuel 24:23) a
              plain note"
      (is (= 1425 (count (re-seq #"(?m)^:::\{small-collapsable " source))))
      (is (= 1423 (count (re-seq #"(?m)^!quote bible:" source))))
      (is (= 1425 (count texts)))
      (is (= ["João 15:35" "1 Samuel 24:23"]
             (map first (filter (comp #(str/includes? % "não localizada") second) texts)))))

    (testing "every quote is exactly one book-quote blockquote, one per proof text"
      (is (= 1423 (count (re-seq #"<blockquote class=\"book-quote\"" html))))
      (is (= 1423 (count quoted)))
      (is (every? (comp some? book-quote second) quoted)))

    (testing "each quote's data-source is its canonical book ID (the shelf
              included) with the passage, and its caption is the summary"
      (is (= 47 (count canonical)) "one generated book per book of blivre.json")
      (doseq [[summary body] quoted]
        (let [{:keys [source title]} (book-quote body)
              {:keys [slug locator]} (passage-of summary)]
          (is (= (str "bible:blivre/" slug "#" locator) source) summary)
          (is (= (str (canonical slug) "#" locator) source) summary)
          (is (= summary title)))))

    (testing "AC #1: each quote shows exactly the verses blivre.json holds
              for it -- verse numbers on a range or a chapter, none on a
              single verse"
      (doseq [[summary body] quoted]
        (let [passage (passage-of summary)]
          (is (seq (:verses passage)) (str summary ": not in blivre.json"))
          (is (= (expected-text passage) (text-of (:html (book-quote body)))) summary)))
      (is (re-find #"<p><strong>34</strong> Jesus lhes respondeu:" html)
          "a verse range keeps its verse numbers")
      (is (= 24 (count (:verses (passage-of "Gênesis 3")))) "Genesis 3 is held whole"))))

(deftest excerpt-quotes-load-the-same-text-test
  (let [{:keys [html diagnostics]} (build-excerpt)
        texts (proof-texts html)]
    (testing "the excerpt is the whole of Lord's Day 1, question 1: 31 proof
              texts, two of them verse ranges, no diagnostics"
      (is (= [] diagnostics) (pr-str diagnostics))
      (is (= 31 (count texts)))
      (is (= 31 (count (re-seq #"<blockquote class=\"book-quote\"" html)))
          "one blockquote per proof text, and no other"))
    (testing "each carries the text of blivre.json"
      (doseq [[summary body] texts]
        (is (= (expected-text (passage-of summary)) (text-of (:html (book-quote body)))) summary)))))

(deftest memory-bible-is-interchangeable-test
  (testing "the same document built against a :memory library of
            in-process virtual books (no libraries.yaml, no shelf.clj)
            produces the same verse text, under the same sources"
    (let [generated (build-excerpt)
          virtual (build-excerpt {:library-directory (memory-bible)})]
      (is (= [] (:diagnostics virtual)) (pr-str (:diagnostics virtual)))
      (is (= 31 (count (proof-texts (:html virtual)))))
      (is (= (mapv (fn [[s body]] [s (text-of body)]) (proof-texts (:html generated)))
             (mapv (fn [[s body]] [s (text-of body)]) (proof-texts (:html virtual)))))
      (is (= (:html generated) (:html virtual))
          "byte for byte: nothing in the output says which kind of book it was")))
  (testing ":library-directory also serves --list-books, which reads no
            directory file at all with it (no :libraries here)"
    (let [{:keys [books diagnostics]} (cli/list-books (merge no-env {:library-directory (memory-bible)})
                                                      "bible")]
      (is (= [] diagnostics))
      (is (= 47 (count books)))
      (is (= ["bible:blivre/joao" "João"] (first (filter #(= "bible:blivre/joao" (first %)) books)))))))

(defn- quote-of
  "Builds a one-quote document against the example library; returns
  `{:html :diagnostics}`."
  [written]
  (let [dir (temp-dir)
        input (io/file dir "q.hdoc")]
    (spit input (str "# Q\n\n!quote " written "\n"))
    (build-html dir input {:libraries (str libraries-file)})))

(deftest library-locators-test
  (testing "a reversed range is reported as reversed, not as missing"
    (let [{:keys [html diagnostics]} (quote-of "bible:joao#8:36-34")]
      (is (= [:bad-locator] (mapv :type diagnostics)) (pr-str diagnostics))
      (is (re-find #"reversed range" (:message (first diagnostics))))
      (is (str/includes? html "?? bible:joao#8:36-34"))))
  (testing "a range only partly in the library is rejected"
    (let [{:keys [diagnostics]} (quote-of "bible:joao#8:33-35")]
      (is (= [:bad-locator] (mapv :type diagnostics)))
      (is (re-find #"only partly" (:message (first diagnostics))))))
  (testing "a verse the library does not hold is rejected"
    (let [{:keys [diagnostics]} (quote-of "bible:joao#8:40")]
      (is (= [:bad-locator] (mapv :type diagnostics)))
      (is (re-find #"not in this library" (:message (first diagnostics))))))
  (testing "a bare chapter answers the verses the library holds of it, as
            shelf.clj documents -- it cannot know the chapter's length"
    (let [{:keys [html diagnostics]} (quote-of "bible:joao#8")]
      (is (= [] diagnostics) (pr-str diagnostics))
      (is (= ["34" "35" "36" "44" "46"] (map second (re-seq #"<strong>(\d+)</strong>" html))))))
  (testing "a chapter held whole is quoted whole"
    (let [{:keys [html diagnostics]} (quote-of "bible:genesis#3")]
      (is (= [] diagnostics) (pr-str diagnostics))
      (is (= (map str (range 1 25)) (map second (re-seq #"<strong>(\d+)</strong>" html)))))))

(deftest licence-is-recorded-test
  (testing "TASK-212: the library's README names the edition, the licence,
            the evidence and the credit upstream asks for, and the example
            repeats the credit"
    (let [readme (slurp (io/file bible-dir "README.md"))
          example (slurp example-file)]
      (doseq [needle ["Bíblia Livre" "CC BY 3.0 Brasil" "creativecommons.org/licenses/by/3.0/br/"
                      "github.com/blivre/BibliaLivre" "a315a15e9f4d01883b62206fe441d57762f126b3"
                      "LICENCA.md" "Diego Renato dos Santos"]]
        (is (str/includes? readme needle) needle))
      (doseq [needle ["Bíblia Livre (BLIVRE)" "Diego Santos, Mario Sérgio e Marco Teles"
                      "creativecommons.org/licenses/by/3.0/br/"]]
        (is (str/includes? example needle) needle))))
  (testing "no source says the withdrawn bible-api.com text is public domain,
            or still uses it: the old verse text and the claim are gone"
    (doseq [f (concat (file-seq (io/file "examples")) (file-seq (io/file "test/fixtures")))
            :when (and (.isFile ^File f) (re-find #"\.(hdoc|json|md|clj|yaml|edn)$" (.getName ^File f))
                       (not (str/includes? (str f) "examples/out/")))]
      (let [content (slurp f)]
        (is (not (re-find #"(?i)domínio público" content)) (str f))
        (is (not (str/includes? content "Replicou-lhes Jesus")) (str f)))))
  (testing "nor does the root README or any backlog document claim a text
            is public domain (the Bible library's README is exempt: it
            names upstream's own claim, as upstream's, and relies on the
            licence instead). A grep is as brittle as the next one, but it
            is what catches the sentence this task removed"
    (doseq [f (concat [(io/file "README.md")]
                      (filter #(str/ends-with? (.getName ^File %) ".md")
                              (file-seq (io/file ".backlog/docs"))))]
      (let [content (slurp f)]
        (is (not (re-find #"(?i)public[- ]domain|domínio público" content)) (str f))))))

(deftest quoted-catechism-compiles-to-pdf-test
  (testing "the quoted excerpt's LaTeX compiles, each quote a quote
            environment closed by its source line"
    (let [dir (temp-dir)
          tex (io/file dir "catecismo.tex")
          {:keys [diagnostics]} (cli/build (merge no-env {:input (str (excerpt-file)) :target "latex"
                                                          :libraries (str libraries-file)
                                                          :output (str tex)}))
          latex (slurp tex)]
      (is (= [] diagnostics) (pr-str diagnostics))
      (is (= 31 (count (re-seq #"(?m)^\\begin\{quote\}$" latex))))
      (is (str/includes? latex "\\textbf{34} Jesus lhes respondeu:"))
      (is (str/includes? latex "{\\raggedleft --- João 8:34-36\\par}"))
      (dotimes [_ 2]
        (shell/sh "pdflatex" "-interaction=nonstopmode" "-halt-on-error" "catecismo.tex" :dir (str dir)))
      (is (.isFile (io/file dir "catecismo.pdf")) "pdflatex must produce a PDF")
      (let [pdf (:out (shell/sh "pdftotext" (str (io/file dir "catecismo.pdf")) "-"))]
        (is (= 31 (count (re-seq #"(?m)^— " pdf))) "one source line per quote")
        (is (str/includes? pdf "Eu e o Pai somos um"))))))
