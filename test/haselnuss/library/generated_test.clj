(deftest script-failed-test
  (testing "a script that throws while loading is located at its line"
    (let [lib (script-library ";; one\n;; two\n(throw (ex-info \"boom\" {}))\n")
          [d & more] (library/library-diagnostics lib)]
      (is (nil? more))
      (is (= :script-failed (:type d)))
      (is (= 3 (:source-line d)))
      (is (str/includes? (:message d) "shelf.clj:3: library \"l\": "))
      (is (str/includes? (:message d) "boom"))
      (testing "and a reference to its books gets that failure"
        (is (= :script-failed (:type (library/find-book lib "a")))))))
  (testing "a syntax error is located too"
    (let [[d] (library/library-diagnostics (script-library "{:books\n (fn [_] [)\n"))]
      (is (= :script-failed (:type d)))
      (is (int? (:source-line d)))))
  (testing "a last form that is not a shelf map"
    (doseq [[script fragment] [["[1 2]" "last form must be a map"]
                               ["{:books (fn [_] [])}" ":document must be a fn"]
                               ["{:books 1 :document (fn [_ _] nil)}" ":books must be a fn"]
                               ["{:books (fn [_] []) :document (fn [_ _] nil) :locate 3}" ":locate must be a fn"]
                               ["{:data \"a.json\" :books (fn [_] []) :document (fn [_ _] nil)}" ":data must be a vector"]
                               ["{:data '(\"a.json\") :books (fn [_] []) :document (fn [_ _] nil)}" ":data must be a vector"]
                               ["{:data [\"a.json\" 3] :books (fn [_] []) :document (fn [_ _] nil)}" "non-blank strings"]]]
      (let [[d] (library/library-diagnostics (script-library script))]
        (is (= :script-failed (:type d)) script)
        (is (str/includes? (:message d) fragment) script))))
  (testing "a last form that would run script code when printed or realised fails inside the timeout"
    ;; Each of these hung the host when the spec was checked on the
    ;; calling thread: printing a stateful toString reify, or realising
    ;; an endless or looping lazy :data. `toString` answers once, then loops.
    (let [looping "(let [n (atom 0)] (reify Object (toString [_] (if (< (swap! n inc) 2) \"ok\" (loop [] (recur))))))"
          fns ":books (fn [_] []) :document (fn [_ _] nil)"]
      (doseq [[label script fragment]
              [["the last form" looping "last form must be a map"]
               [":books" (str "{:books " looping " :document (fn [_ _] nil)}") ":books must be a fn"]
               [":locate" (str "{" fns " :locate " looping "}") ":locate must be a fn"]
               [":data" (str "{" fns " :data " looping "}") ":data must be a vector"]
               ["an item of :data" (str "{" fns " :data [" looping "]}") "plain data only"]
               ["an endless lazy :data" (str "{" fns " :data (repeat \"a.json\")}") ":data must be a vector"]
               ["an endless :data vector's items"
                (str "{" fns " :data [(repeat \"a.json\")]}") "output cap"]
               ["a looping lazy :data" (str "{" fns " :data (map (fn [_] (loop [] (recur))) [1])}")
                ":data must be a vector"]
               ["a looping lazy item of :data" (str "{" fns " :data [(map (fn [_] (loop [] (recur))) [1])]}")
                "did not finish within 1000ms"]
               ["deeply nested :data" (str "{" fns " :data [(reduce (fn [a _] [a]) [] (range 100000))]}")
                "StackOverflowError"]]]
        (let [start (System/nanoTime)
              [d & more] (library/library-diagnostics (script-library script {} {:timeout-ms 1000}))
              elapsed-ms (/ (- (System/nanoTime) start) 1e6)]
          (is (nil? more) label)
          (is (= :script-failed (:type d)) label)
          (is (str/includes? (str (:message d)) fragment) (str label ": " (:message d)))
          (is (< elapsed-ms 10000) (str label " took " elapsed-ms "ms"))))))
  (testing ":books that throws or answers no sequence of maps"
    (doseq [[books fragment] [["(fn [_]\n (/ 1 0))" "Divide by zero"]
                              ["(fn [_] {:slug \"a\"})" "sequence of maps"]
                              ["(fn [_] [1 2])" "sequence of maps"]]]
      (let [[d] (library/library-diagnostics
                 (script-library (str "{:books " books " :document (fn [_ _] nil)}")))]
        (is (= :script-failed (:type d)) books)
        (is (str/includes? (:message d) fragment) books))))
  (testing "a script that never finishes loading times out"
    (let [lib (script-library "(loop [] (recur))" {} {:timeout-ms 300})
          [d] (library/library-diagnostics lib)]
      (is (= :script-failed (:type d)))
      (is (str/includes? (:message d) "did not finish within 300ms"))))
  (testing "a :document that throws, loops or exceeds the output cap fails only its book"
    (doseq [[label document opts fragment]
            [["throws" "(throw (ex-info \"no such book\" {}))" {} "no such book"]
             ["loops" "(loop [] (recur))" {:timeout-ms 300} "did not finish within 300ms"]
             ["a huge string" "{:meta {} :blocks [{:t :para :inlines [{:t :str :text (apply str (repeat 5000 \"x\"))}]}]}"
              {:document-output-limit 1000} "1000-character cap"]
             ["an endless lazy seq inside the result" "{:meta {} :blocks (map identity (range))}"
              {:document-output-limit 1000 :timeout-ms 5000} "1000-character cap"]
             ;; Printing either reify runs script code; the second print
             ;; of the toString one, and every deref of the IDeref one,
             ;; loops. Both must fail inside the timeout, not hang the
             ;; host when it prints the result later.
             ["a reify with a stateful toString in :meta"
              (str "{:meta {:x (let [n (atom 0)] (reify Object (toString [_] (if (< (swap! n inc) 2)"
                   " \"ok\" (loop [] (recur))))))} :blocks []}")
              {:timeout-ms 2000} "plain data only"]
             ["an IDeref reify" "{:meta {:x (reify clojure.lang.IDeref (deref [_] (loop [] (recur))))} :blocks []}"
              {:timeout-ms 2000} "plain data only"]
             ["a fn" "{:meta {:f (fn [] 1)} :blocks []}" {} "plain data only"]
             ["an atom" "{:meta {:a (atom 1)} :blocks []}" {} "plain data only"]]]
      (let [lib (one-book-library document "nil" opts)
            start (System/nanoTime)
            d (library/document (library/find-book lib "a"))
            elapsed-ms (/ (- (System/nanoTime) start) 1e6)]
        (is (= :script-failed (:type d)) label)
        (is (= "l:s/a" (:book d)) label)
        (is (str/includes? (:message d) fragment) (str label ": " (:message d)))
        (is (< elapsed-ms 10000) (str label " took " elapsed-ms "ms"))
        (is (= ["l:s/a"] (ids lib)) label)
        (is (= [] (library/library-diagnostics lib)) label))))
  (testing ":books and :locate answers must be plain data too"
    (let [[d] (library/library-diagnostics
               (script-library "{:books (fn [_] [{:slug \"a\" :title (reify Object (toString [_] \"A\"))}]) :document (fn [_ _] nil)}"))]
      (is (= :script-failed (:type d)))
      (is (str/includes? (:message d) "plain data only")))
    (let [p (library/locate (library/find-book (one-book-library valid-doc "{:title \"T\" :blocks [] :x (atom 1)}" {}) "a")
                            "1:1")]
      (is (= :script-failed (:type p)))))
  (testing "a :document gets a larger cap than :books and :locate: half a megabyte is fine"
    (let [doc (str "{:meta {} :blocks (vec (for [i (range 2500)] {:t :para :inlines"
                   " [{:t :str :text (apply str (repeat 200 \"x\"))}]}))}")
          lib (one-book-library doc "nil" {})
          d (library/document (library/find-book lib "a"))]
      (is (ast/valid? ast/Document d) (pr-str (:message d)))
      (is (< 500000 (count (pr-str d))))
      (is (= 2000000 generated/default-document-output-limit))))
  (testing "metadata on a result is dropped, so a script cannot forge a source position"
    (let [lib (one-book-library (str "{:meta {} :blocks [(with-meta {:t :para :inlines [{:t :str :text \"x\"}]}"
                                     " {:haselnuss.ast/source {:line 1 :file \"/etc/passwd\"}})]}")
                                "nil" {})
          d (library/document (library/find-book lib "a"))]
      (is (ast/valid? ast/Document d))
      (is (nil? (ast/source (first (:blocks d)))))
      (is (nil? (meta (first (:blocks d)))))))
  (testing "a :locate that throws is a script-failed at its line"
    (let [lib (one-book-library valid-doc "(do\n (/ 1 0))" {})
          p (library/locate (library/find-book lib "a") "1:1")]
      (is (= :script-failed (:type p)))
      (is (= 4 (:source-line p))))))

