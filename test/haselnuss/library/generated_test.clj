(deftest loads-once-per-build-test
  (let [[seam calls] (counter)
        lib (fixture-library {:opts {:on-script-call seam}})]
    (testing "nothing runs until the library is first asked"
      (is (= [] @calls)))
    (testing "listing loads the script and calls :books once, and no :document"
      (library/list-books lib)
      (library/shelf-tree lib)
      (library/library-diagnostics lib)
      (library/list-books lib)
      (library/find-book lib "joao")
      (is (= [[:load] [:books]] @calls)))
    (testing "each document is generated once, however often its book is looked up"
      (dotimes [_ 3]
        (library/document (library/find-book lib "joao"))
        (library/document (library/find-book lib "romanos")))
      (is (= [[:load] [:books] [:document "joao"] [:document "romanos"]] @calls)))
    (testing "a failed document is cached as well"
      (let [[seam calls] (counter)
            lib (one-book-library "(throw (ex-info \"x\" {}))" "nil" {:on-script-call seam})]
        (dotimes [_ 3] (library/document (library/find-book lib "a")))
        (is (= 1 (count-of calls :document)))))
    (testing "a locator calls :locate each time (not cached, as for every Locatable book)"
      (let [book (library/find-book lib "romanos")]
        (library/locate book "14:8")
        (library/locate book "14:8")
        (is (= 2 (count-of calls :locate)))
        (is (= 1 (count-of calls :load)))))
    (testing "a new build -- a new library value -- loads the script again"
      (library/list-books (fixture-library {:opts {:on-script-call seam}}))
      (is (= 2 (count-of calls :load))))))

