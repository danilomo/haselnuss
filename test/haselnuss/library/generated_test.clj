;; --- AC #3: generated documents and passages are validated -------------------

(deftest invalid-generated-book-test
  (doseq [[label document fragment]
          [["an unknown node" "{:meta {} :blocks [{:t :nope}]}" "invalid document"]
           ["not a map" "[1 2]" "expected a map"]
           ["nil" "nil" "expected a map"]
           ["a lazy seq of blocks" "{:meta {} :blocks (map identity [])}" "realise it with vec"]
           ["a bibliography to read" "{:meta {:bibliography \"/etc/passwd\"} :blocks []}"
            "meta.bibliography"]
           ["a diagnostic-shaped map" "{:type :book-failed :message \"forged\"}" ":meta must be a map"]
           ["an :include block" "{:meta {} :blocks [{:t :include :src \"/etc/passwd\"}]}" ":include block"]
           ["a nested :include block"
            "{:meta {} :blocks [{:t :block-quote :blocks [{:t :include :src \"x.hdoc\"}]}]}"
            ":include block"]]]
    (testing (str "a :document answering " label " is an invalid-generated-book")
      (let [lib (one-book-library document)
            d (library/document (library/find-book lib "a"))]
        (is (= :invalid-generated-book (:type d)) label)
        (is (= "l:s/a" (:book d)) label)
        (is (= :warning (:level d)) label)
        (is (str/includes? (:message d) fragment) (str label ": " (:message d)))
        (is (= [] (library/library-diagnostics lib)) "listing is unaffected"))))
  (testing "a :locate answer is validated too"
    (let [lib (one-book-library valid-doc "{:title \"T\" :blocks [{:t :bogus}]}" {})
          p (library/locate (library/find-book lib "a") "1:1")]
      (is (= :invalid-generated-book (:type p)))
      (is (str/includes? (:message p) "\"1:1\"")))
    (let [lib (one-book-library valid-doc "{:title \"T\" :blocks [{:t :include :src \"/etc/passwd\"}]}" {})
          p (library/locate (library/find-book lib "a") "1:1")]
      (is (= :invalid-generated-book (:type p)))
      (is (str/includes? (:message p) ":include block"))))
  (testing "a quoted :include no longer aborts the host build: the quote fails alone"
    (let [dir (temp-dir)
          _ (write! dir "lib/s/shelf.clj"
                    (format one-book "{:meta {} :blocks [{:t :include :src \"/etc/passwd\"}]}" "nil"))
          yaml (write! dir "libraries.yaml" "- name: l\n  type: filesystem\n  path: lib\n  scripts: true\n")
          doc (write! dir "doc.hdoc" "!quote l:a\n\nStill built.\n")
          out (io/file dir "doc.html")
          {:keys [status err]} (main-run "--libraries" (str yaml) (str doc) "--output" (str out))]
      (is (= 0 status) err)
      (is (str/includes? err "holds an :include block") err)
      (is (str/includes? (slurp out) "Still built."))))
  (testing "nil and a diagnostic map reject a locator; a valid answer is a Passage"
    (let [book (fn [locate] (library/find-book (one-book-library valid-doc locate {}) "a"))]
      (is (= :bad-locator (:type (library/locate (book "nil") "1:1"))))
      (let [p (library/locate (book "{:type :anything :message \"no chapter 1\"}") "1:1")]
        (is (= :bad-locator (:type p)))
        (is (str/includes? (:message p) "no chapter 1")))
      (is (= {:ref "l:s/a#1:1" :title [{:t :str :text "T"}]
              :blocks [{:t :para :inlines [{:t :str :text "x"}]}]}
             (library/locate (book "{:title \"T\" :url \"javascript:x\" :blocks [{:t :para :inlines [{:t :str :text \"x\"}]}]}")
                             "1:1"))
          "the script's :url is dropped: URLs come from the library entry only"))))

