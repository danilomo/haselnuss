(def ^:private kinds (into #{} (map name) (keys resolver/default-lexicon)))

(defn- directory-file
  "A library directory file naming the fixture library `bible`, with
  `extra` YAML lines for its entry."
  [extra]
  (write! (temp-dir) "libraries.yaml"
          (str "- name: bible\n  type: filesystem\n  path: " fixture-root "\n" extra)))

(defn- books-option [file]
  (references/books-option
   {:directory (references/directory-loader
                {:path (str file)
                 :registry (directory/register-provider directory/default-registry :filesystem
                                                        (fs/provider {:kinds kinds}))})
    :context (passage/context)}))

(defn- quotes [document] (filterv #(= :book-quote (:t %)) (:blocks document)))

(deftest passages-resolve-like-any-book-test
  (let [file (directory-file "  scripts: true\n")
        source (str "!quote bible:romanos#14:8\n\n"
                    "!quote bible:joao#8:34-36\n\n"
                    "!quote bible:scripture/hebreus#cap:2\n\n"
                    "!quote bible:romanos\n\n"
                    "See @{bible:joao#6:39} and @{bible:hebreus#cap:2}.\n\n"
                    "!quote bible:joao#99:1\n")
        {:keys [document diagnostics]}
        (resolver/resolve-document (parser/parse source {:source "host.hdoc"})
                                   {:books (books-option file)})
        [verse verses label whole bad] (quotes document)]
    (testing "a locator passage is the script's :locate"
      (is (= "bible:scripture/romanos#14:8" (:canonical verse)))
      (is (= "Romanos 14:8" (text-of (:title verse))))
      (is (str/starts-with? (text-of (:inlines (first (:blocks verse))))
                            "Pois, se vivemos, para o Senhor vivemos"))
      (is (= 3 (count (:blocks verses))) "8:34-36 is three verses"))
    (testing "a label passage and a whole book come from the generated document"
      (is (= "bible:scripture/hebreus#cap:2" (:canonical label)))
      (is (= :section (:t (first (:blocks label)))))
      (is (= "bible:scripture/romanos" (:canonical whole)))
      (is (= "Romanos" (text-of (:title whole)))))
    (testing "links take the passage's title as their text (a label of a kind the
              lexicon does not number prints as itself)"
      (let [refs (filterv #(= :book-ref (:t %)) (:inlines (last (filter #(= :para (:t %)) (:blocks document)))))]
        (is (= ["João 6:39" "Hebreus, cap:2"] (mapv (comp text-of :text) refs)))))
    (testing "a locator the script finds nothing at is a bad-locator, at the host's line"
      (is (nil? (:canonical bad)))
      (let [[w & more] (by-type diagnostics :bad-locator)]
        (is (nil? more))
        (is (= "bible:joao#99:1" (:ref w)))
        (is (= 11 (:source-line w)))))
    (is (= [:bad-locator] (mapv :type diagnostics)))))

;; --- AC #2: data confined to the shelf, no file access from the script ------

(deftest data-files-test
  (testing "JSON, YAML and EDN are parsed by the host, keyed by the path as written"
    (let [lib (script-library
               (str "{:data [\"a.json\" \"sub/b.yaml\" \"c.edn\"]\n"
                    " :books (fn [d] [{:slug \"x\" :title (str (get-in d [\"a.json\" :t]) \"/\""
                    " (get-in d [\"sub/b.yaml\" :t]) \"/\" (get-in d [\"c.edn\" :t]))}])\n"
                    " :document (fn [_ _] " valid-doc ")}\n")
               {"s/a.json" "{\"t\": \"json\"}" "s/sub/b.yaml" "t: yaml\n" "s/c.edn" "{:t \"edn\"}"})]
      (is (= [] (library/library-diagnostics lib)))
      (is (= [{:t :str :text "json/yaml/edn"}] (:title (first (library/list-books lib)))))))
  (testing "a :data path outside the shelf folder is refused"
    (doseq [[label written files] [["a parent path" "../outside.json" {"outside.json" "{}"}]
                                   ["a sibling shelf" "../t/x.json" {"t/x.json" "{}"}]
                                   ["an absolute path" (str (io/file (temp-dir) "abs.json")) {}]]]
      (let [lib (script-library (str "{:data [" (pr-str written) "] :books (fn [_] []) "
                                     ":document (fn [_ _] nil)}")
                                files)
            [d & more] (library/library-diagnostics lib)]
        (is (nil? more) label)
        (is (= :script-failed (:type d)) label)
        (is (= written (:data d)) label)
        (is (re-find #"absolute|outside the shelf folder" (:message d)) label)
        (is (= [] (library/list-books lib)) label))))
  (testing "a symlink inside the shelf folder that points outside it is refused"
    (let [dir (temp-dir)
          outside (write! dir "secret.json" "{\"k\": 1}")
          _ (write! dir "s/shelf.clj" "{:data [\"link.json\"] :books (fn [_] []) :document (fn [_ _] nil)}")
          linked? (try (Files/createSymbolicLink (.toPath (io/file dir "s" "link.json")) (.toPath outside)
                                                 (make-array FileAttribute 0))
                       true
                       (catch Exception _ false))]
      (when linked?
        (let [lib (fs/filesystem-library {:name "l" :path (str dir) :scripts true})]
          (is (= [:script-failed] (mapv :type (library/library-diagnostics lib))))
          (is (str/includes? (:message (first (library/library-diagnostics lib)))
                             "outside the shelf folder"))))))
  (testing "a path the JDK rejects fails only its shelf, not the whole library"
    (let [dir (temp-dir)
          _ (write! dir "s/shelf.clj" "{:data [\"a\\u0000.json\"] :books (fn [_] []) :document (fn [_ _] nil)}")
          _ (write! dir "disk/kept.hdoc" "---\ntitle: Kept\n---\n")
          lib (fs/filesystem-library {:name "l" :path (str dir) :scripts true})
          [d & more] (library/library-diagnostics lib)]
      (is (= ["l:disk/kept"] (ids lib)))
      (is (nil? more))
      (is (= :script-failed (:type d)))
      (is (str/includes? (:message d) "not a usable path") (:message d))))
  (testing "a missing, unparseable or unsupported data file is a script-failed"
    (doseq [[label written files fragment] [["missing" "nope.json" {} "no such file"]
                                            ["bad JSON" "bad.json" {"s/bad.json" "{oops"} "cannot read it"]
                                            ["a .txt" "notes.txt" {"s/notes.txt" "x"} ".json, .yaml"]]]
      (let [lib (script-library (str "{:data [" (pr-str written) "] :books (fn [_] []) "
                                     ":document (fn [_ _] nil)}")
                                files)
            [d] (library/library-diagnostics lib)]
        (is (= :script-failed (:type d)) label)
        (is (str/includes? (:message d) fragment) label)))))

