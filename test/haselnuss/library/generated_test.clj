(ns haselnuss.library.generated-test
  "Generated shelves (TASK-158, doc-10 \"Generator scripts\"): a
  `shelf.clj` in a filesystem library's shelf folder, run in
  `haselnuss.sandbox`, yields that shelf's books.

  `test/fixtures/libraries/generated/` is the committed fixture: the
  generated shelf `scripture/` (three books over a JSON and an EDN data
  file, with chapter:verse locators) beside an ordinary book. Scripts
  that must fail -- throw, loop, read files, answer invalid AST -- are
  written to temp folders. Script calls are counted through the
  provider's `:on-script-call` seam, never `with-redefs`.

  Timeouts use a short, test-local `:timeout-ms`; on this project's JDK
  the sandbox stops an abandoned worker (TASK-147), so a looping script
  leaves no spinning thread behind."
  (:require [clojure.java.io :as io]
            [clojure.string :as str]
            [clojure.test :refer [deftest is testing]]
            [haselnuss.ast :as ast]
            [haselnuss.book-ref :as book-ref]
            [haselnuss.cli :as cli]
            [haselnuss.library :as library]
            [haselnuss.library.contract :as contract]
            [haselnuss.library.directory :as directory]
            [haselnuss.library.filesystem :as fs]
            [haselnuss.library.generated :as generated]
            [haselnuss.library.passage :as passage]
            [haselnuss.library.references :as references]
            [haselnuss.parser :as parser]
            [haselnuss.resolver :as resolver])
  (:import (java.io File)
           (java.nio.file Files)
           (java.nio.file.attribute FileAttribute)))

;; --- helpers -----------------------------------------------------------------

(def ^:private fixture-root
  (.getAbsolutePath (io/file "test/fixtures/libraries/generated")))

(def ^:private script-path
  (str (io/file fixture-root "scripture" "shelf.clj")))

(defn- temp-dir ^File []
  (.toFile (Files/createTempDirectory "haselnuss-generated" (make-array FileAttribute 0))))

(defn- write!
  ^File [^File dir rel text]
  (let [file (io/file dir rel)]
    (io/make-parents file)
    (spit file text)
    file))

(defn- counter
  "An `:on-script-call` seam and an atom of every call it saw, as
  `[kind & args]` (the script path dropped)."
  []
  (let [calls (atom [])]
    [(fn [kind _path & args] (swap! calls conj (into [kind] args))) calls]))

(defn- count-of [calls kind] (count (filter #(= kind (first %)) @calls)))

(defn- fixture-library
  "The fixture library named `bible`, scripts on unless `scripts` says
  otherwise."
  ([] (fixture-library {}))
  ([{:keys [scripts opts] :or {scripts true}}]
   (fs/filesystem-library (cond-> {:name "bible" :path fixture-root}
                            (some? scripts) (assoc :scripts scripts))
                          (or opts {}))))

(defn- script-library
  "A library `l` whose only shelf `s` is generated by `script`, with
  `files` (relative path -> text) written beside it. `opts` are the
  provider's."
  ([script] (script-library script {} {}))
  ([script files] (script-library script files {}))
  ([script files opts]
   (let [dir (temp-dir)]
     (write! dir "s/shelf.clj" script)
     (doseq [[rel text] files] (write! dir rel text))
     (fs/filesystem-library {:name "l" :path (str dir) :scripts true} opts))))

(defn- by-type [diagnostics t] (filter #(= t (:type %)) diagnostics))

(defn- ids [lib] (mapv (comp book-ref/format-book-id :id) (library/list-books lib)))

(def ^:private one-book
  "A script listing one book `a` whose document is `document` (a form)."
  "{:books (fn [_] [{:slug \"a\" :title \"A\"}])\n :document (fn [_ _] %s)\n :locate (fn [_ _ loc] %s)}\n")

(defn- one-book-library
  "A library over `one-book` with `document` and `locate` forms."
  ([document] (one-book-library document "nil" {}))
  ([document locate opts]
   (script-library (format one-book document locate) {} opts)))

(def ^:private valid-doc "{:meta {} :blocks [{:t :para :inlines [{:t :str :text \"x\"}]}]}")

(defn- fm-title [s] (:title (parser/front-matter (str "---\ntitle: " s "\n---\n"))))

(defn- text-of [inlines]
  (apply str (map #(case (:t %) :str (:text %) :space " " (text-of (:inlines %))) inlines)))

(def ^:private no-libraries {:library-env {} :library-home "/nonexistent/haselnuss-test-home"})

(defn- main-run
  "`cli/main*` over `args` with no real library directory, as `{:status
  :out :err}`."
  [& args]
  (let [err (java.io.StringWriter.)
        out (java.io.StringWriter.)
        status (binding [*err* err *out* out] (cli/main* args no-libraries))]
    {:status status :out (str out) :err (str err)}))

